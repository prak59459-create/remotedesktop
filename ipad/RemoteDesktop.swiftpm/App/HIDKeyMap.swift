import UIKit

/// Windows へ送るキー
enum RemoteKey: Equatable {
    case scancode(UInt16) // PC/AT セット 1 (拡張キーは 0xE0xx)
    case virtualKey(UInt16)

    func event(down: Bool) -> ClientEvent {
        switch self {
        case .scancode(let c): return .key(code: c, down: down, virtualKey: false)
        case .virtualKey(let c): return .key(code: c, down: down, virtualKey: true)
        }
    }
}

/// iPad のハードウェアキーボード (USB HID usage) → Windows のスキャンコード
enum HIDKeyMap {
    static func remoteKey(_ usage: UIKeyboardHIDUsage, commandAsControl: Bool) -> RemoteKey? {
        let u = usage.rawValue
        switch u {
        case 0xE3: return .scancode(commandAsControl ? 0x1D : 0xE05B) // 左 ⌘
        case 0xE7: return .scancode(commandAsControl ? 0xE01D : 0xE05C) // 右 ⌘
        case 0x90: return .virtualKey(0x16) // LANG1 (かな) → VK_IME_ON
        case 0x91: return .virtualKey(0x1A) // LANG2 (英数) → VK_IME_OFF
        default: return table[u].map { .scancode($0) }
        }
    }

    private static let table: [Int: UInt16] = {
        var t: [Int: UInt16] = [:]
        // A-Z
        let letters: [UInt16] = [0x1E, 0x30, 0x2E, 0x20, 0x12, 0x21, 0x22, 0x23, 0x17, 0x24, 0x25, 0x26, 0x32,
                                 0x31, 0x18, 0x19, 0x10, 0x13, 0x1F, 0x14, 0x16, 0x2F, 0x11, 0x2D, 0x15, 0x2C]
        for (i, sc) in letters.enumerated() { t[0x04 + i] = sc }
        // 1-9, 0
        for i in 0 ..< 10 { t[0x1E + i] = UInt16(0x02 + i) }
        let rest: [(Int, UInt16)] = [
            (0x28, 0x1C), (0x29, 0x01), (0x2A, 0x0E), (0x2B, 0x0F), (0x2C, 0x39), (0x2D, 0x0C), (0x2E, 0x0D),
            (0x2F, 0x1A), (0x30, 0x1B), (0x31, 0x2B), (0x32, 0x2B), (0x33, 0x27), (0x34, 0x28), (0x35, 0x29),
            (0x36, 0x33), (0x37, 0x34), (0x38, 0x35), (0x39, 0x3A),
            // F1-F12
            (0x3A, 0x3B), (0x3B, 0x3C), (0x3C, 0x3D), (0x3D, 0x3E), (0x3E, 0x3F), (0x3F, 0x40), (0x40, 0x41),
            (0x41, 0x42), (0x42, 0x43), (0x43, 0x44), (0x44, 0x57), (0x45, 0x58),
            (0x46, 0xE037), (0x47, 0x46), (0x49, 0xE052), (0x4A, 0xE047), (0x4B, 0xE049), (0x4C, 0xE053),
            (0x4D, 0xE04F), (0x4E, 0xE051), (0x4F, 0xE04D), (0x50, 0xE04B), (0x51, 0xE050), (0x52, 0xE048),
            // テンキー
            (0x53, 0x45), (0x54, 0xE035), (0x55, 0x37), (0x56, 0x4A), (0x57, 0x4E), (0x58, 0xE01C),
            (0x59, 0x4F), (0x5A, 0x50), (0x5B, 0x51), (0x5C, 0x4B), (0x5D, 0x4C), (0x5E, 0x4D), (0x5F, 0x47),
            (0x60, 0x48), (0x61, 0x49), (0x62, 0x52), (0x63, 0x53), (0x64, 0x56), (0x65, 0xE05D),
            // JIS
            (0x87, 0x73), (0x88, 0x70), (0x89, 0x7D), (0x8A, 0x79), (0x8B, 0x7B),
            // 修飾キー
            (0xE0, 0x1D), (0xE1, 0x2A), (0xE2, 0x38), (0xE4, 0xE01D), (0xE5, 0x36), (0xE6, 0xE038),
        ]
        for (k, v) in rest { t[k] = v }
        return t
    }()
}
